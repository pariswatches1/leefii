export default function USMap({ stateData }: USMapProps) {
  const router = useRouter()
  const [tooltip, setTooltip] = useState<{
    x: number
    y: number
    name: string
    status: StateMapData['status']
  } | null>(null)
  const [hoveredState, setHoveredState] = useState<string | null>(null)

  const stateMap = new Map(stateData.map((s) => [s.abbreviation, s]))

  function getColor(abbr: string): string {
    const data = stateMap.get(abbr)
    if (!data) return '#d1d5db'
    return STATUS_COLORS[data.status]
  }

  function handleMouseMove(
    e: React.MouseEvent<SVGPathElement>,
    abbr: string
  ) {
    const data = stateMap.get(abbr)
    if (!data) return
    const rect = (
      e.currentTarget.closest('svg') as SVGSVGElement
    ).getBoundingClientRect()
    setTooltip({
      x: e.clientX - rect.left,
      y: e.clientY - rect.top - 40,
      name: data.name,
      status: data.status,
    })
    setHoveredState(abbr)
  }

  function handleMouseLeave() {
    setTooltip(null)
    setHoveredState(null)
  }

  function handleClick(abbr: string) {
    const data = stateMap.get(abbr)
    if (!data) return
    router.push(`/laws/${data.slug}`)
  }

  return (
    <div className="relative w-full max-w-5xl mx-auto">
      <svg
        viewBox="0 0 960 600"
        className="w-full h-auto"
        xmlns="http://www.w3.org/2000/svg"
      >
        {Object.entries(STATE_PATHS).map(([abbr, d]) => {
          const isHovered = hoveredState === abbr
          const fill = getColor(abbr)
          return (
            <path
              key={abbr}
              d={d}
              data-state={abbr}
              fill={fill}
              stroke="#fff"
              strokeWidth={1.5}
              style={{
                cursor: 'pointer',
                filter: isHovered ? 'brightness(0.8)' : 'none',
                transition: 'filter 0.15s ease',
              }}
              onMouseMove={(e) => handleMouseMove(e, abbr)}
              onMouseLeave={handleMouseLeave}
              onClick={() => handleClick(abbr)}
            />
          )
        })}
      </svg>

      {tooltip && (
        <div
          className="pointer-events-none absolute z-50 rounded-lg bg-gray-900 px-3 py-2 text-sm text-white shadow-lg"
          style={{
            left: tooltip.x,
            top: tooltip.y,
            transform: 'translate(-50%, -100%)',
          }}
        >
          <p className="font-semibold">{tooltip.name}</p>
          <p
            className="text-xs"
            style={{ color: STATUS_COLORS[tooltip.status] }}
          >
            {STATUS_LABELS[tooltip.status]}
          </p>
        </div>
      )}

      {/* Legend */}
      <div className="mt-4 flex flex-wrap items-center justify-center gap-4 text-sm">
        {(
          Object.entries(STATUS_LABELS) as [StateMapData['status'], string][]
        ).map(([status, label]) => (
          <div key={status} className="flex items-center gap-1.5">
            <span
              className="inline-block h-3.5 w-3.5 rounded-sm"
              style={{ backgroundColor: STATUS_COLORS[status] }}
            />
            <span className="text-gray-700 dark:text-gray-300">{label}</span>
          </div>
        ))}
      </div>
    </div>
  )
}
